import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import {randomBytes} from "node:crypto";

test("fila manual respeita consentimento, lembretes, modelos e confirmação explícita",async()=>{
  const temp=fs.mkdtempSync(path.join(os.tmpdir(),"agenda-whatsapp-"));
  process.env.DATABASE_PATH=path.join(temp,"app.sqlite");process.env.INSTALL_TOKEN=randomBytes(32).toString("hex");
  process.env.NODE_ENV="test";process.env.DEMO_MODE="false";
  const {default:app}=await import("../src/app.js"),{db}=await import("../src/database.js");
  const server=app.listen(0,"127.0.0.1");await new Promise(r=>server.once("listening",r));
  let cookie="";
  const call=async(route,method="GET",body)=>{
    const response=await fetch("http://127.0.0.1:"+server.address().port+"/api"+route,{method,headers:{...(body?{"Content-Type":"application/json"}:{}),...(cookie?{Cookie:cookie}:{})},body:body?JSON.stringify(body):undefined});
    const next=response.headers.get("set-cookie");if(next)cookie=next.split(";")[0];return {status:response.status,body:await response.json()};
  };
  try{
    assert.equal((await call("/installation/setup","POST",{businessName:"Salão",slug:"whatsapp-test",ownerName:"Dono",ownerEmail:"owner@whatsapp.local",password:"Senha-Forte-Whatsapp-123",installToken:process.env.INSTALL_TOKEN})).status,201);
    const login=await call("/auth/login","POST",{email:"owner@whatsapp.local",password:"Senha-Forte-Whatsapp-123"});assert.equal(login.status,200);
    const tenant=login.body.user.tenantId;
    const prefs=(await call("/whatsapp/preferences")).body;assert.equal(prefs.mode,"manual");
    const create=async(name,phone,whatsappConsent=false,whatsappMarketingConsent=false)=>(await call("/clients","POST",{name,phone,whatsappConsent,whatsappMarketingConsent})).body.client.id;
    const c=await create("Cliente","85912345678",true,true),other=await create("Sem consentimento","85912345679");
    db.prepare("INSERT INTO users(id,tenant_id,name,email,password_hash,role) VALUES(?,?,?,?,?,'profissional')").run("wh-pro",tenant,"Profissional","pro@whatsapp.local","hash");
    db.prepare("INSERT INTO services(id,tenant_id,name,duration_minutes,price_cents) VALUES(?,?,?,?,?)").run("wh-service",tenant,"Corte",30,5000);
    const future=new Intl.DateTimeFormat("sv-SE",{timeZone:"America/Sao_Paulo",year:"numeric",month:"2-digit",day:"2-digit",hour:"2-digit",minute:"2-digit",second:"2-digit",hourCycle:"h23"}).format(new Date(Date.now()+3600000)).replace(" ","T");
    const add=db.prepare("INSERT INTO appointments(id,tenant_id,client_id,professional_id,service_id,starts_at,ends_at,status,price_cents,booking_source,whatsapp_opt_in) VALUES(?,?,?,?,?,?,?,'confirmado',5000,?,?)");
    const end=new Intl.DateTimeFormat("sv-SE",{timeZone:"America/Sao_Paulo",year:"numeric",month:"2-digit",day:"2-digit",hour:"2-digit",minute:"2-digit",second:"2-digit",hourCycle:"h23"}).format(new Date(Date.now()+5400000)).replace(" ","T");
    add.run("internal",tenant,c,"wh-pro","wh-service",future,end,"internal",0);
    add.run("no-consent",tenant,other,"wh-pro","wh-service",future,end,"internal",0);
    add.run("public-no-consent",tenant,c,"wh-pro","wh-service",future,end,"public",0);
    add.run("public-optin",tenant,other,"wh-pro","wh-service",future,end,"public",1);
    const sync=async()=>(await call("/whatsapp/sync","POST")).body.messages;
    let messages=await sync();assert.equal(messages.length,4);
    assert.equal(messages.filter(m=>m.appointmentId==="internal").length,2);
    assert.equal(messages.some(m=>m.appointmentId==="public-no-consent"),false);
    assert.equal(messages.some(m=>m.appointmentId==="no-consent"),false);
    const notice=messages.find(m=>m.appointmentId==="internal"&&m.kind==="confirmado");
    assert.match(notice.message,/Cliente.*Corte.*Profissional/);
    assert.equal((await sync()).find(m=>m.id===notice.id).id,notice.id);
    const action=(id,op)=>call("/whatsapp/messages/"+id+"/"+op,"POST");
    assert.equal((await action(notice.id,"sent")).status,409);
    assert.equal((await action(notice.id,"open")).body.phone,"5585912345678");
    assert.equal((await sync()).find(m=>m.id===notice.id).sentAt,null);
    assert.equal((await action(notice.id,"sent")).status,200);
    assert.equal((await action(notice.id,"sent")).status,409);
    assert.equal((await sync()).find(m=>m.id===notice.id).sentByName,"Dono");
    const reminder=messages.find(m=>m.appointmentId==="internal"&&m.kind==="lembrete");
    assert.equal((await action(reminder.id,"open")).status,200);
    // Preferences change invalidates previous prepared text.
    prefs.rules.lembrete.template="Lembrete: {cliente}, {servico}, {hora}.";
    assert.equal((await call("/whatsapp/preferences","PUT",prefs)).status,200);
    assert.equal((await action(reminder.id,"sent")).status,409);
    assert.match((await sync()).find(m=>m.id===reminder.id).message,/Lembrete:/);
    const today=(await call("/cash/daily")).body.today;
    assert.equal((await call("/cash/openings","POST",{date:today,openingCashCents:0})).status,201);
    const pkg=await call("/packages","POST",{name:"Pacote Corte",priceCents:8000,validityDays:3,items:[{serviceId:"wh-service",sessions:2}]});
    assert.equal(pkg.status,201);
    assert.equal((await call("/packages/"+pkg.body.id+"/sell","POST",{clientId:c,priceCents:8000,paymentMethod:"pix",requestId:"wa-test-package-001"})).status,201);
    assert.equal((await call("/direct-services","POST",{clientId:c,serviceId:"wh-service",professionalId:"wh-pro",paymentMethod:"pix"})).status,201);
    assert.equal((await call("/loyalty/settings","PUT",{enabled:true,threshold:1,discountCents:1000})).status,200);
    prefs.rules.fidelidade.enabled=true;
    assert.equal((await call("/whatsapp/preferences","PUT",prefs)).status,200);
    messages=await sync();
    assert.match(messages.find(m=>m.kind==="pacote").message,/Pacote Corte.*2 sessão/);
    assert.match(messages.find(m=>m.kind==="fidelidade").message,/1 pontos.*R\$ 10,00/);
    assert.equal((await call("/clients/"+c,"PATCH",{name:"Cliente",phone:"85912345678",whatsappConsent:false,whatsappMarketingConsent:false})).status,200);
    assert.equal((await action(reminder.id,"open")).status,409);
    assert.equal((await sync()).some(m=>m.id===reminder.id),false);
    assert.equal((await sync()).some(m=>["pacote","fidelidade"].includes(m.kind)),false);
    assert.equal((await sync()).some(m=>m.id===notice.id&&m.sentAt),true);
    assert.equal((await call("/clients/"+other,"PATCH",{name:"Sem consentimento",phone:"85912345670",whatsappConsent:true})).status,200);
    assert.equal(db.prepare("SELECT whatsapp_opt_in FROM appointments WHERE id='public-optin'").get().whatsapp_opt_in,0);
    assert.equal((await sync()).some(m=>m.appointmentId==="public-optin"),false);
    const ownerHash=db.prepare("SELECT password_hash FROM users WHERE tenant_id=? AND role='dono'").get(tenant).password_hash;
    db.prepare("INSERT INTO users(id,tenant_id,name,email,password_hash,role) VALUES(?,?,?,?,?,'recepcao')").run("wh-reception",tenant,"Recepção","reception@whatsapp.local",ownerHash);
    assert.equal((await call("/auth/login","POST",{email:"reception@whatsapp.local",password:"Senha-Forte-Whatsapp-123"})).status,200);
    assert.equal((await call("/whatsapp/preferences","PUT",prefs)).status,403);
    assert.equal((await call("/whatsapp/sync","POST")).status,200);
  }finally{await new Promise(r=>server.close(r));db.close();fs.rmSync(temp,{recursive:true,force:true});}
});
